# Run from repository root:
#   powershell -ExecutionPolicy Bypass -File .\tools\Build-StandaloneRelease.ps1

$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent (Split-Path -Parent $PSCommandPath)
$SrcDir = Join-Path $RepoRoot "src"
$ReleaseDir = Join-Path $RepoRoot "releases"
$VendorWacsDir = Join-Path $RepoRoot "vendor\win-acme"
$OutputPath = Join-Path $ReleaseDir "Install-CertGuard-PA-Standalone.ps1"

$Files = @(
    "certguard_agent.py",
    "certguard_gui.py",
    "certguard_gui_qt.py",
    "certguard_windows_service.py",
    "certguard_eventlog.py",
    "certguard_secrets.py"
)

function Convert-FileToBase64Text {
    param([string]$Path)
    $bytes = [System.IO.File]::ReadAllBytes($Path)
    return [Convert]::ToBase64String($bytes)
}

New-Item -ItemType Directory -Force -Path $ReleaseDir | Out-Null

$WacsZipB64 = ""
$WacsExe = Join-Path $VendorWacsDir "wacs.exe"
if (Test-Path $WacsExe) {
    $TempZip = Join-Path $env:TEMP ("certguard-win-acme-" + [guid]::NewGuid().ToString("N") + ".zip")
    try {
        Compress-Archive -Path (Join-Path $VendorWacsDir "*") -DestinationPath $TempZip -Force
        $WacsZipB64 = [Convert]::ToBase64String([System.IO.File]::ReadAllBytes($TempZip))
        Write-Host "[INFO] Bundled win-acme runtime: $VendorWacsDir"
    } finally {
        Remove-Item $TempZip -Force -ErrorAction SilentlyContinue
    }
} else {
    Write-Warning "Bundled win-acme runtime not found. Run .\tools\Import-WinAcmeVendor.ps1 first."
}

$Embedded = @{}
foreach ($file in $Files) {
    $path = Join-Path $SrcDir $file
    if (-not (Test-Path $path)) {
        throw "Required source file not found: $path"
    }
    $Embedded[$file] = Convert-FileToBase64Text $path
}

$Template = @'
# CertGuard-PA Standalone Installer
# Generated by tools/Build-StandaloneRelease.ps1
# ASCII only

param(
    [ValidateSet("Install","InstallSilent","Uninstall","Start","Stop","Restart","Status","Gui","GuiLegacy","Debug","Deploy","ForceDeploy","Policy","Compare","InspectPfx","TestApi","TestWacs","TestCloudflare","ProvisionWacs","RenewWacs","Health","Repair")]
    [string]$Action = "Install"
)

$ErrorActionPreference = "Stop"

$ServiceName = "CertGuard-PA"
$DisplayName = "CertGuard-PA Certificate Monitor"
$InstallDir = "C:\ProgramData\CertGuard-PA"
$LogDir = Join-Path $InstallDir "logs"
$Agent = Join-Path $InstallDir "certguard_agent.py"
$Gui = Join-Path $InstallDir "certguard_gui_qt.py"
$GuiLegacy = Join-Path $InstallDir "certguard_gui.py"
$ServiceHost = Join-Path $InstallDir "certguard_windows_service.py"
$RuntimeInstaller = Join-Path $InstallDir "Install-CertGuard-PA.ps1"
$ManagedWacsDir = Join-Path $InstallDir "win-acme"
$ManagedWacsExe = Join-Path $ManagedWacsDir "wacs.exe"
$ManagedWacsDataDir = Join-Path $InstallDir "win-acme-data"
$ManagedWacsLogDir = Join-Path $LogDir "win-acme"
$EmbeddedWacsZip = "__WACS_ZIP_B64__"

$EmbeddedFiles = @{
    "certguard_agent.py" = "__AGENT_B64__"
    "certguard_gui.py" = "__GUI_LEGACY_B64__"
    "certguard_gui_qt.py" = "__GUI_QT_B64__"
    "certguard_windows_service.py" = "__SERVICE_HOST_B64__"
    "certguard_eventlog.py" = "__EVENTLOG_B64__"
    "certguard_secrets.py" = "__SECRETS_B64__"
}

function Assert-Admin {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object Security.Principal.WindowsPrincipal($identity)
    if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
        throw "Run PowerShell as Administrator."
    }
}

function Get-PythonCommand {
    $py = Get-Command python -ErrorAction SilentlyContinue
    if ($py) { return "python" }
    $pyLauncher = Get-Command py -ErrorAction SilentlyContinue
    if ($pyLauncher) { return "py" }
    throw "Python 3 was not found in PATH."
}

function Get-PythonPrefix {
    $py = Get-Command python -ErrorAction SilentlyContinue
    if ($py) { return @() }
    return @("-3")
}

function Invoke-PythonChecked {
    param([string[]]$Arguments)
    $py = Get-PythonCommand
    $prefix = Get-PythonPrefix
    & $py @prefix @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "Python command failed with exit code ${LASTEXITCODE}: $($Arguments -join ' ')"
    }
}

function Invoke-PythonOptional {
    param([string[]]$Arguments)
    $py = Get-PythonCommand
    $prefix = Get-PythonPrefix
    $oldEap = $ErrorActionPreference
    try {
        $ErrorActionPreference = "Continue"
        & $py @prefix @Arguments 1>$null 2>$null
        return ($LASTEXITCODE -eq 0)
    } catch {
        return $false
    } finally {
        $ErrorActionPreference = $oldEap
    }
}

function Test-PythonImport {
    param([string]$ModuleName)
    return Invoke-PythonOptional @("-c", "import $ModuleName")
}

function Test-PythonServiceHost {
    $py = Get-PythonCommand
    if ($py -eq "python") {
        try {
            $pythonExe = (Get-Command python).Source
            $pythonDir = Split-Path -Parent $pythonExe
            return (Test-Path (Join-Path $pythonDir "pythonservice.exe"))
        } catch {
            return $false
        }
    }
    return $true
}

function Ensure-Package {
    param([string]$ModuleName, [string]$PackageName)
    if (Test-PythonImport $ModuleName) {
        Write-Host "[INFO] Python package already available: $PackageName"
        return
    }
    Write-Host "[INFO] Python package missing or broken: $PackageName. Installing/upgrading..."
    Invoke-PythonChecked @("-m", "pip", "install", "--upgrade", "--force-reinstall", $PackageName)
    if (-not (Test-PythonImport $ModuleName)) {
        throw "Python package installation completed but import still failed: $PackageName"
    }
}

function Ensure-Dependencies {
    Ensure-Package "cryptography" "cryptography"
}

function Ensure-ServiceDependencies {
    Ensure-Dependencies
    Ensure-Package "win32serviceutil" "pywin32"
    if (Test-PythonServiceHost) {
        Write-Host "[INFO] Python service host is available"
        return
    }
    if (Invoke-PythonOptional @("-m", "pywin32_postinstall", "-install")) {
        Write-Host "[INFO] pywin32 postinstall completed"
    } else {
        Write-Host "[INFO] pywin32 postinstall module not available; continuing because pywin32 imports are valid"
    }
}

function Ensure-GuiDependencies {
    Ensure-Dependencies
    Ensure-Package "PySide6" "PySide6"
}

function Ensure-EventSource {
    # CertGuard-PA runtime events follow the Cloudflare-DDNS-Windows pattern:
    # pywin32 servicemanager writes Windows Application events and owns the message resource behavior.
    # Do not register or modify a custom EventMessageFile mapping here.
    Write-Host "[INFO] Event Log handled by pywin32 servicemanager"
}

function Write-EmbeddedFile {
    param([string]$Name, [string]$TargetPath)
    $base64 = $EmbeddedFiles[$Name]
    $bytes = [Convert]::FromBase64String($base64)
    [System.IO.File]::WriteAllBytes($TargetPath, $bytes)
}

function Deploy-WinAcme {
    if ([string]::IsNullOrWhiteSpace($EmbeddedWacsZip)) {
        return
    }
    New-Item -ItemType Directory -Force -Path $ManagedWacsDir | Out-Null
    $tempZip = Join-Path $env:TEMP ("certguard-win-acme-" + [guid]::NewGuid().ToString("N") + ".zip")
    try {
        [System.IO.File]::WriteAllBytes($tempZip, [Convert]::FromBase64String($EmbeddedWacsZip))
        Get-ChildItem $ManagedWacsDir -Force -ErrorAction SilentlyContinue | Remove-Item -Recurse -Force -ErrorAction SilentlyContinue
        Expand-Archive -Path $tempZip -DestinationPath $ManagedWacsDir -Force
    } finally {
        Remove-Item $tempZip -Force -ErrorAction SilentlyContinue
    }
    if (-not (Test-Path $ManagedWacsExe)) {
        throw "Bundled win-acme deployment failed: $ManagedWacsExe"
    }

    New-Item -ItemType Directory -Force -Path $ManagedWacsDataDir | Out-Null
    New-Item -ItemType Directory -Force -Path $ManagedWacsLogDir | Out-Null
    $settingsDefault = Join-Path $ManagedWacsDir "settings_default.json"
    $settingsPath = Join-Path $ManagedWacsDir "settings.json"
    if (Test-Path $settingsDefault) {
        $settings = Get-Content $settingsDefault -Raw | ConvertFrom-Json
        $settings.Client.ClientName = "CertGuard-PA-WACS"
        $settings.Client.ConfigurationPath = $ManagedWacsDataDir
        $settings.Client.LogPath = $ManagedWacsLogDir
        $settings | ConvertTo-Json -Depth 100 | Set-Content $settingsPath -Encoding UTF8
    }
    Write-Host "[INFO] Bundled win-acme deployed to $ManagedWacsDir"
    Write-Host "[INFO] win-acme state isolated at $ManagedWacsDataDir"
}

function Deploy-Files {
    New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
    New-Item -ItemType Directory -Force -Path $LogDir | Out-Null

    foreach ($name in $EmbeddedFiles.Keys) {
        Write-EmbeddedFile $name (Join-Path $InstallDir $name)
    }

    Deploy-WinAcme

    try {
        $sourcePath = [System.IO.Path]::GetFullPath($PSCommandPath)
        $targetPath = [System.IO.Path]::GetFullPath($RuntimeInstaller)
        if ($sourcePath -ne $targetPath) {
            Copy-Item $PSCommandPath $RuntimeInstaller -Force
        }
    } catch {
        Write-Warning "Runtime installer copy failed: $($_.Exception.Message)"
    }

    try {
        icacls $InstallDir /inheritance:e | Out-Null
        icacls $InstallDir /grant:r "Administrators:(OI)(CI)F" "SYSTEM:(OI)(CI)F" | Out-Null
    } catch {
        Write-Warning "ACL update failed: $($_.Exception.Message)"
    }

    Write-Host "[INFO] Embedded files deployed to $InstallDir"
}

function Invoke-Agent {
    param([string]$Command)
    Deploy-Files
    Ensure-Dependencies
    Invoke-PythonChecked @($Agent, $Command)
}

function Remove-ServiceIfExists {
    sc.exe query $ServiceName *> $null
    if ($LASTEXITCODE -eq 0) {
        sc.exe stop $ServiceName *> $null
        Start-Sleep -Seconds 2
        sc.exe delete $ServiceName *> $null
        Start-Sleep -Seconds 2
        Write-Host "[INFO] Service removed: $ServiceName"
    } else {
        Write-Host "[INFO] Service does not exist: $ServiceName"
    }
}

function Install-Service {
    Deploy-Files
    Ensure-ServiceDependencies
    Ensure-EventSource

    Remove-ServiceIfExists

    Invoke-PythonChecked @($ServiceHost, "install")

    sc.exe config $ServiceName start= auto | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "sc.exe config start= auto failed." }

    sc.exe description $ServiceName "CertGuard-PA automated Palo Alto certificate lifecycle monitor." | Out-Null
    sc.exe failure $ServiceName reset= 86400 actions= restart/60000/restart/120000/restart/300000 | Out-Null
    sc.exe failureflag $ServiceName 1 | Out-Null

    Invoke-PythonChecked @($ServiceHost, "start")
    Write-Host "[INFO] Service installed and started: $ServiceName"
}

function Uninstall-App {
    Remove-ServiceIfExists

    if (-not (Test-Path $InstallDir)) {
        Write-Host "[INFO] ProgramData directory does not exist."
        return
    }

    Write-Host ""
    Write-Host "ProgramData cleanup options:"
    Write-Host "  1 - Remove everything: config, state, logs and runtime files"
    Write-Host "  2 - Keep config/state, remove runtime files only"
    Write-Host "  3 - Remove logs only"
    Write-Host "  4 - Keep everything"
    $choice = Read-Host "Select cleanup option (1/2/3/4)"

    switch ($choice) {
        "1" {
            Remove-Item $InstallDir -Recurse -Force -ErrorAction SilentlyContinue
            Write-Host "[INFO] Removed all ProgramData: $InstallDir"
        }
        "2" {
            Get-ChildItem $InstallDir -File -Filter "*.py" -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue
            Write-Host "[INFO] Runtime files removed; config/state/logs preserved."
        }
        "3" {
            Remove-Item $LogDir -Recurse -Force -ErrorAction SilentlyContinue
            Write-Host "[INFO] Logs removed."
        }
        default {
            Write-Host "[INFO] ProgramData preserved."
        }
    }
}

function Show-Status {
    sc.exe query $ServiceName
    $statePath = Join-Path $InstallDir "state.json"
    if (Test-Path $statePath) {
        Write-Host ""
        Write-Host "[STATE]"
        Get-Content $statePath
    }
}

